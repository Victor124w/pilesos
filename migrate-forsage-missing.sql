-- Учёт пропавших кодов Форсажа (миграция 2026-08-10).
--
-- ЗАЧЕМ. В `forsage_scans.missing` пишется, СКОЛЬКО кодов из базы не встретилось в проходе,
-- но не КАКИЕ. По одному числу решение принять нельзя: за 10.08 счётчик гулял 0 → 853 → 1
-- при НУЛЕВЫХ сбоях запросов, то есть Magento сам отдаёт то полный каталог, то на сотню
-- позиций меньше. Разовое отсутствие — шум выдачи, устойчивое — снятый с продажи товар,
-- и различить их можно только по СЕРИИ проходов.
--
-- ПОЧЕМУ НЕ `last_seen` В `forsage_products`. Очевидное решение — штамповать «видели» каждому
-- товару в каждом проходе — стоит 43 000 записей в час (>1 млн в сутки). Сейчас за проход
-- пишутся десятки строк (только изменения) — см. комментарий в forsage-run.mjs. Поэтому
-- пишем не увиденных, а пропавших: их единицы-сотни, и они же сразу отвечают на вопрос «какие».
--
-- Строка живёт, пока код отсутствует. Встретился снова — строка удаляется (серия оборвалась).
-- Таблица служебная: товарных данных в ней нет, `forsage_products` она не трогает.
--
-- Применять: wrangler d1 execute prices_db --remote --file migrate-forsage-missing.sql

CREATE TABLE IF NOT EXISTS forsage_missing (
  code           TEXT PRIMARY KEY,      -- sku Magento, тот же, что в forsage_products
  name           TEXT,                  -- денормализовано: отчёты строятся без join
  category       TEXT,
  first_missing  INTEGER NOT NULL,      -- начало ТЕКУЩЕЙ серии отсутствия (не «пропал впервые»)
  last_missing   INTEGER NOT NULL,      -- последний проход, где кода не было
  misses         INTEGER NOT NULL DEFAULT 1  -- проходов подряд без него; серия рвётся возвратом
);
CREATE INDEX IF NOT EXISTS idx_forsage_missing_misses ON forsage_missing (misses);
