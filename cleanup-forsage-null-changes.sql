-- РАЗОВАЯ ЧИСТКА (2026-08-08). Удаляет ложные «изменения цены», порождённые миграцией на доллар.
--
-- Что произошло: колонки price_retail_usd / price_partner_usd добавлены пустыми, и на первом
-- же прогоне после миграции diff увидел переход NULL → значение у КАЖДОГО товара, по обеим
-- ценам. Получилось 86 154 записи вместо реальных двух (обе — про наличие).
--
-- Критерий безопасный: у настоящего изменения цены `old_val` всегда заполнен, а строки
-- про наличие (`field='stock'`) не трогаются вовсе. Проверено перед удалением:
--   всего 86156 · под критерий попадает 86154 · остаётся 2 настоящих.
--
-- Применять: wrangler d1 execute prices_db --remote --file cleanup-forsage-null-changes.sql

DELETE FROM forsage_changes
 WHERE old_val IS NULL
   AND field IN ('retail', 'partner');
